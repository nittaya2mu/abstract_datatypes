/* คืนข้อมูลเรือตามชนิด -- O(1) */
const BoatInfo *boat_info(BoatType t) {
    if (t < 0 || t >= BOAT_TYPE_COUNT) return NULL;
    return &BOAT_INFO[t];
}

/* คืนชื่อไทยของเรือ -- O(1) */
const char *boat_name(BoatType t) {
    const BoatInfo *b = boat_info(t);
    return b ? b->name : "ไม่ทราบชนิด";
}

/* เรือชนิด t วิ่งในวัน day หรือไม่ (day: 0=อาทิตย์ .. 6=เสาร์) -- O(1) */
int boat_runs_on_day(BoatType t, int day) {
    const BoatInfo *b = boat_info(t);
    if (!b || day < 0 || day >= DAY_COUNT) return 0;
    return b->service_days[day];
}

/* แปลงนาทีเป็นข้อความ "HH:MM"  (out ต้องมีที่ว่างอย่างน้อย 6 ไบต์) */
void minutes_to_hhmm(int minutes, char *out) {
    if (!out) return;
    if (minutes < 0) minutes = 0;
    sprintf(out, "%02d:%02d", (minutes / 60) % 24, minutes % 60);
}

/* นับจำนวน "ตัวอักษร" ของสตริง UTF-8 (ไม่ใช่จำนวนไบต์) -- O(len)
   หลักการ: ไบต์ที่เป็นส่วนต่อของตัวอักษรเดิมจะขึ้นต้นด้วยบิต 10xxxxxx
   จึงนับเฉพาะไบต์ที่ไม่ใช่รูปแบบนั้น
   หมายเหตุ: สระบนล่างและวรรณยุกต์ไทยถูกนับเป็น 1 ตัวด้วย ความกว้างจึงยังไม่ตรงเป๊ะ
   ในทุกกรณี แต่ตรงกว่าการนับไบต์แบบเดิมมาก */
int utf8_display_width(const char *s) {
    int w = 0;
    if (!s) return 0;
    while (*s) {
        unsigned char ch = (unsigned char)*s;
        if ((ch & 0xC0) != 0x80) w++;   /* ไม่ใช่ไบต์ต่อเนื่อง = ตัวอักษรใหม่ */
        s++;
    }
    return w;
}

/* พิมพ์สตริงแล้วเติมช่องว่างท้ายให้ได้ความกว้างตามต้องการ -- O(len + width) */
void print_padded(const char *s, int width) {
    int w;
    if (!s) s = "";
    printf("%s", s);
    w = utf8_display_width(s);
    { int i; for (i = w; i < width; i++) printf(" "); }
}

/* พิมพ์ตารางเวลาเดินเรือและวันให้บริการทั้งหมด */
void data_print_boat_schedule(void) {
    char buf[8];

    printf("\n========== ตารางเดินเรือ ==========\n");
    { int t; for (t = 0; t < BOAT_TYPE_COUNT; t++) {
        const BoatInfo *b = &BOAT_INFO[t];
        printf("\n[%d] %s\n", t, b->name);

        printf("    รอบเวลาออก :");
        { int i; for (i = 0; i < b->depart_count; i++) {
            minutes_to_hhmm(b->depart_times[i], buf);
            printf("  %s น.", buf);
        } }
        printf("\n    วันให้บริการ:");
        { int d; for (d = 0; d < DAY_COUNT; d++)
            if (b->service_days[d]) printf("  %s", DAY_NAME_TH[d]); }
        printf("\n    วันหยุด     :");
        { int d; for (d = 0; d < DAY_COUNT; d++)
            if (!b->service_days[d]) printf("  %s", DAY_NAME_TH[d]); }
        printf("\n");
    } }
    printf("===================================\n");
}
